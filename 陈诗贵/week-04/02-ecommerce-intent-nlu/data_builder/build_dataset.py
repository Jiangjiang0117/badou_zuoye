PREFIXES = ["", "请问", "你好", "麻烦问一下", "我想问一下"]
SUFFIXES = ["", "？", "呢？", "啊？"]


def _normalize(seed_line: str, idx: int, mode: int) -> str:
    """对单条种子生成变体。

    mode=0：原句（缺标点则补问号）
    mode=1：加前缀变体
    """
    line = seed_line.strip()
    if not line:
        return ""
    if mode == 0:
        return line if line.endswith(("？", "?", "。")) else line + "？"
    prefix = PREFIXES[idx % len(PREFIXES)]
    if not prefix:
        return ""
    return prefix + "，" + line + "？"


def build_dataset() -> None:
    random.seed(RANDOM_SEED)

    samples = []
    for category in CATEGORY_NAME:
        seed_text = SEEDS[category]
        seed_lines = [ln for ln in seed_text.splitlines() if ln.strip()]
        for idx, line in enumerate(seed_lines):
            for mode in (0, 1):
                variant = _normalize(line, idx, mode)
                if variant:
                    samples.append((variant, category))

    # 去重（保留类别），再随机打乱
    unique = list(dict.fromkeys(samples))
    random.shuffle(unique)

    os.makedirs(os.path.dirname(DATASET_PATH), exist_ok=True)
    with open(DATASET_PATH, "w", encoding="utf-8") as f:
        for text, label in unique:
            f.write(f"{text}\t{label}\n")

    # 打印各类别统计
    from collections import Counter
    stat = Counter(label for _, label in unique)
    print(f"共生成 {len(unique)} 条样本")
    for category in CATEGORY_NAME:
        print(f"  {category}: {stat.get(category, 0)}")


if __name__ == "__main__":
    build_dataset()
